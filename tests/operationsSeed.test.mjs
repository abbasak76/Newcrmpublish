import assert from 'node:assert/strict';
import { generateSeedData } from '../src/lib/seed.ts';
const state = generateSeedData();
assert.ok(state.salesOrders.length >= 2, 'test orders seeded');
assert.ok(state.dispatchPlans.length >= 1, 'test dispatch plans seeded');
assert.ok(state.salesReturns.length >= 1, 'test returns seeded');
assert.ok(state.commercialPolicies.length >= 2, 'test policies seeded');
assert.ok(state.reconciliationCases.length >= 2, 'test reconciliation cases seeded');
assert.ok(state.suppliers.length >= 2, 'test suppliers seeded');
assert.ok(state.purchaseRequests.length >= 1, 'test purchase requests seeded');
for (const order of state.salesOrders) {
  assert.equal(order.source, 'LOCAL_TEST');
  assert.ok(state.accounts.some(c => c.id === order.customerId), `order customer exists: ${order.id}`);
  for (const line of order.lines) assert.ok(state.externalProducts.some(p => p.id === line.productId), `order product exists: ${line.productId}`);
}
assert.equal(state.salesReturns[0].financialDocumentConfirmed, false);
assert.equal(state.salesReturns[0].invoiceId, null);
assert.equal(state.seedMetadata.mode, 'LOCAL_TEST');
console.log('operationsSeed: PASS (16 assertions)');
import { applyDemoSeed } from '../src/lib/seed.ts';
const demoState = generateSeedData();
applyDemoSeed(demoState);
const demoOrders = demoState.salesOrders.filter(o => o.id.startsWith('demo-'));
assert.ok(demoOrders.length >= 12, 'FMCG demo orders seeded');
assert.ok(demoState.dispatchPlans.some(p => p.id.startsWith('demo-')), 'FMCG dispatch plans seeded');
assert.ok(demoState.salesReturns.filter(r => r.id.startsWith('demo-')).length >= 4, 'demo returns seeded');
assert.ok(demoState.externalProducts.some(p => p.id.startsWith('demo-') && Number(p.weightKgPerUnit) > 0), 'demo product weight estimates seeded');
assert.ok(demoOrders.every(o => o.source === 'LOCAL_TEST' && o.lines.every(line => demoState.externalProducts.some(p => p.id === line.productId))), 'demo order lines resolve to seeded products');
const repeatReport = applyDemoSeed(demoState);
assert.equal(demoState.salesOrders.filter(o => o.id.startsWith('demo-')).length, demoOrders.length, 'demo seed is idempotent for orders');
assert.ok(repeatReport.skipped > 0, 'repeated demo seed skips duplicate IDs');
console.log('operationsSeed FMCG: PASS (7 assertions)');
assert.ok(demoState.accounts.filter(c => c.id.startsWith('demo-')).length >= 80, 'expanded demo customer coverage');
assert.ok(demoState.quotes.filter(q => q.id.startsWith('demo-')).length >= 240, 'expanded quote volume');
assert.ok(demoState.invoices.filter(i => i.id.startsWith('demo-')).length >= 100, 'expanded invoice volume');
assert.ok(demoState.payments.filter(p => p.id.startsWith('demo-')).length >= 60, 'expanded payment volume');
assert.ok(demoState.cheques.filter(c => c.id.startsWith('demo-')).length >= 50, 'incoming and payable cheques seeded');
assert.ok(demoState.expenses.filter(e => e.id.startsWith('demo-')).length >= 90, 'six months of expense data seeded');
assert.ok(demoState.supplierBills.filter(b => b.id.startsWith('demo-')).length >= 45, 'supplier bill and payable data seeded');
assert.ok(demoState.salesOrders.filter(o => o.id.startsWith('demo-')).length >= 60, 'expanded order volume');
assert.ok(demoState.dispatchPlans.filter(p => p.id.startsWith('demo-')).length >= 12, 'expanded dispatch planning volume');
console.log('operationsSeed expanded finance: PASS (9 assertions)');
