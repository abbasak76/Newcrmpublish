import assert from 'node:assert/strict';
import { reconcileReceivables } from '../src/lib/receivableReconciliation.ts';
const invoice={id:'i1',invoiceNumber:'INV-1',customerId:'c1',accountId:'c1',totalAmount:1000,paidAmount:200,balance:700,status:'PARTIAL',date:'2026-10-01',dueDate:'2026-10-10'};
const payments=[{id:'p1',customerId:'c1',accountId:'c1',amount:200,status:'CLEARED',method:'TRANSFER',date:'2026-10-05'}];
const allocations=[{id:'a1',paymentId:'p1',invoiceId:'i1',amount:200,createdAt:'2026-10-05'}];
const posted={id:'cn1',externalCreditNoteId:'ERP-CN-1',sourceSystemCode:'ERP',sourceType:'ERP_MIRROR',customerId:'c1',accountId:'c1',invoiceId:'i1',amount:100,status:'POSTED',sourceDocumentId:'ERP-CN-22',syncedAt:'2026-10-12',createdAt:'2026-10-12',postedAt:'2026-10-12'};
const report=reconcileReceivables([invoice],payments,allocations,[posted],new Date('2026-10-27T00:00:00Z'));
assert.equal(report.creditSourceAvailable,true);
assert.equal(report.authoritative,true);
assert.equal(report.totalValidAllocated,200);
assert.equal(report.totalValidCredits,100);
assert.equal(report.totalOutstandingBeforeCredits,800);
assert.equal(report.totalOutstanding,700);
assert.equal(report.customerOutstanding.c1,700);
assert.equal(report.invoices[0].validCreditAmount,100);
assert.equal(report.invoices[0].daysOverdue,17);
assert.equal(report.priorities[0].customerId,'c1');
assert.equal(report.priorities[0].outstandingAmount,700);
const pending=reconcileReceivables([{...invoice,balance:800}],payments,allocations,[{...posted,status:'PENDING_APPROVAL'}],new Date('2026-10-27T00:00:00Z'));
assert.equal(pending.totalOutstanding,800,'unposted credit does not reduce receivables');
assert.equal(pending.authoritative,true,'unposted workflow records do not block the posted-ledger balance');
const crossCustomer=reconcileReceivables([{...invoice,balance:800}],payments,allocations,[{...posted,customerId:'c2'}]);
assert.equal(crossCustomer.totalValidCredits,0);
assert.equal(crossCustomer.authoritative,false);
assert.ok(crossCustomer.issues.some(i=>i.code==='CREDIT_NOTE_CUSTOMER_MISMATCH'));
const overCredit=reconcileReceivables([{...invoice,balance:0}],payments,allocations,[{...posted,amount:900}]);
assert.ok(overCredit.issues.some(i=>i.code==='CREDIT_NOTE_OVERALLOCATED'));
assert.equal(overCredit.authoritative,false);
const noSource=reconcileReceivables([invoice],payments,allocations);
assert.equal(noSource.authoritative,false);
assert.equal(noSource.priorities.length,0,'ranking is blocked when credit source is not supplied');
console.log('PASS: 16 assertions (posted credit notes, balances, source validation, overdue priorities and blocked ranking)');
const approved=reconcileReceivables([{...invoice,balance:700}],payments,allocations,[{...posted,status:'APPROVED'}],new Date('2026-10-27T00:00:00Z'));
assert.equal(approved.totalValidCredits,100,'approved ERP mirror credits match the canonical SQL view contract');
const voided=reconcileReceivables([{...invoice,balance:800}],payments,allocations,[{...posted,isVoided:true}]);
assert.equal(voided.totalValidCredits,0,'voided ERP mirror credits never reduce the balance');
const wrongSource=reconcileReceivables([{...invoice,balance:800}],payments,allocations,[{...posted,sourceType:'LOCAL_REQUEST'}]);
assert.equal(wrongSource.authoritative,false,'local requests cannot be passed off as ERP mirror credits');
assert.ok(wrongSource.issues.some(i=>i.code==='CREDIT_NOTE_SOURCE_INVALID'));
console.log('PASS: 20 assertions after approved/voided/source-isolation cases');
