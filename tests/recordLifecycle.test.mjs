import assert from 'node:assert/strict';
import { activeRecords, isRecordDeleted, markRecordDeleted, restoreRecord } from '../src/lib/recordLifecycle.ts';
const live = { id: 'a', name: 'active' };
const deletedAt = { id: 'b', deletedAt: '2026-01-01T00:00:00Z' };
const deletedFlag = { id: 'c', isDeleted: true };
assert.equal(isRecordDeleted(live), false);
assert.equal(isRecordDeleted(deletedAt), true);
assert.equal(isRecordDeleted(deletedFlag), true);
assert.deepEqual(activeRecords([live, deletedAt, deletedFlag]).map(x => x.id), ['a']);
assert.deepEqual(activeRecords(undefined), []);
const marked = markRecordDeleted(live, 'user-1', '2026-10-28T12:00:00Z');
assert.equal(marked.deleted, true);
assert.equal(marked.deletedBy, 'user-1');
assert.equal(marked.id, live.id);
const restored = restoreRecord(marked, 'admin-1', '2026-10-28T13:00:00Z');
assert.equal(isRecordDeleted(restored), false);
assert.equal(restored.restoredBy, 'admin-1');
assert.equal(restored.id, live.id);
console.log('PASS: 10 record lifecycle assertions');
